#!/usr/bin/env node
/**
 * seed-preview-raffle.js
 *
 * Writes a .env.lhci file that configures the Vite preview build to use
 * demo data (VITE_USE_DEMO_DATA=true), making /raffles/101 resolve
 * deterministically to the "Tesla Model 3 Performance" fixture from
 * src/data/demoRaffles.ts.
 *
 * Run automatically by the "lighthouse:build" script before lhci autorun.
 * The file is written to client/ root so Vite picks it up as a lowest-
 * priority .env override (Vite loads .env files in this order:
 *   .env < .env.local < .env.[mode] < .env.[mode].local)
 * We write to .env.lhci and load it via --mode lhci in the preview call so
 * it never clashes with developer-local overrides.
 *
 * Usage:  node scripts/seed-preview-raffle.js
 */

import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const envContent = `# Auto-generated by scripts/seed-preview-raffle.js — do not edit manually.
# Loaded only during Lighthouse CI runs (vite preview --mode lhci).
VITE_USE_DEMO_DATA=true
VITE_APP_ENV=development
VITE_DEBUG_MODE=false
`;

const envPath = resolve(root, '.env.lhci');
writeFileSync(envPath, envContent, 'utf8');

console.log(`[seed-preview-raffle] Wrote ${envPath}`);
console.log('[seed-preview-raffle] Lighthouse detail-page seed: /raffles/101 (Tesla Model 3 Performance)');
